def _flat(value: Optional[str]) -> str:
    return re.sub(r"\s+", "", str(value or "").strip().strip('"')).lower()


def app_owned_filter(result: Optional[cfgscan.ScanResult]) -> Callable[[Any], bool]:
    """A test for ``gamewatch`` changes that a map setup made, not the player.

    A key counts when it is one a setup binds and either side of the change
    is that setup's bind (loaded, or put back afterwards). A setting counts
    the same way.
    """
    if result is None:
        return lambda change: False
    setups = setups_for(load(), result)
    if not setups:
        return lambda change: False
    found = touched(result, [s["file"] for s in setups])
    keys = {physical: {_flat(b) for b in bodies}
            for physical, (_spelled, bodies) in found["keys"].items()}
    settings = {name.lower(): {_flat(v) for v in values}
                for name, values in found["settings"].items()}

    def owned(change: Any) -> bool:
        if change.source in ("Key binds", "Stick binds"):
            bodies = keys.get(cfgscan.physical_key(change.key))
            return bool(bodies) and (_flat(change.now) in bodies or _flat(change.was) in bodies)
        if change.source == "In-game settings":
            values = settings.get(change.key.lower())
            return bool(values) and (_flat(change.now) in values or _flat(change.was) in values)
        return False

    return owned


