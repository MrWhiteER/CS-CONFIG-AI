"""Map setups: practice and match configs that only last while you are on a map.

Configs like a warmup or a 5v5 server setup rebind keys (noclip on Mouse 3,
"give me health" on E ...) and change settings. Loaded by hand, they used to
stay on long after the practice map was gone: through the next official
match, and -- because CS2 saves every bind when it closes -- into the next
launch too, where the app then reported them as "buttons you changed".

A map setup is one of those configs plus the maps it belongs to. The player
still loads it the way they always did (their own key). The app does the
other half:

* It follows which map the game is on through CS2's own game state feed
  (the same one the Stats tab records matches with).
* While the player is on a map a setup belongs to, nothing is touched, so
  pressing the apply key there never undoes the warmup.
* The moment they leave that map -- back to the menu, another map, quitting
  or a crash -- the app writes ``cfg/cs2cfg_map_reset.cfg``: every key,
  script and setting the setups touch, put back to the player's normal ones.
  The apply key file ends with ``exec cs2cfg_map_reset``, and once the
  player is in the main menu with CS2 in front, the app presses the apply
  key once for them (Edy, Nov 22). Never during a match.
* "Back to normal" is remembered on disk, so after a quit or a crash the
  same happens the first time the game reaches the main menu again.
* What CS2 saved of a setup's binds at shutdown is the app's own doing, so
  it never shows up as "buttons you changed".

No game file is edited and no wait timer is used: every step reacts to what
the game reports.
"""

from __future__ import annotations

import json
import re
import threading
import time
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Set, Tuple

from . import cfglang, cfgscan

FILE_NAME = "cs2cfg_map_reset.cfg"
EXEC_NAME = FILE_NAME.rsplit(".", 1)[0]
EXEC_LINE = f"exec {EXEC_NAME}"
MARKER = "// GENERATED BY cs2-autoconfig -- DO NOT EDIT BY HAND"
STORE_NAME = "map-setups.json"
_STATE_LOCK = threading.RLock()

# A settings line that only means something on the server a setup runs.
# They die with that server, so there is nothing to put back.
_SERVER_PREFIXES = ("mp_", "bot_", "sv_", "cash_", "ammo_", "ff_", "host_",
                    "spec_", "tv_", "ent_", "weapon_", "mp ", "nav_")


# ---------------------------------------------------------------------------
# What the player picked
# ---------------------------------------------------------------------------

def _store() -> Path:
    from .paths import user_data_dir

    return user_data_dir() / STORE_NAME


def load() -> Dict[str, Any]:
    try:
        data = json.loads(_store().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        data = {}
    if not isinstance(data, dict):
        data = {}
    setups = data.get("setups")
    data["setups"] = [s for s in setups if isinstance(s, dict) and s.get("file")] \
        if isinstance(setups, list) else []
    data.setdefault("auto_press", True)
    data.setdefault("needs_reset", False)
    return data


def save(data: Dict[str, Any]) -> None:
    from . import fileio

    with _STATE_LOCK:
        path = _store()
        path.parent.mkdir(parents=True, exist_ok=True)
        fileio.write_text(path, json.dumps(data, indent=1))


def update(changes: Dict[str, Any]) -> Dict[str, Any]:
    with _STATE_LOCK:
        data = load()
        data.update(changes)
        save(data)
        return data


def remember_baseline(result, bindings=None, settings=None, source="saved game settings"):
    """Record a normal baseline before practice, never from an owed restore."""
    if result is None:
        return
    with _STATE_LOCK:
        data = load()
        if data.get('needs_reset'):
            return
        data['baseline'] = {'root': str(result.root.resolve()),
                            'keys': {cfgscan.physical_key(k): str(v) for k,v in (bindings or {}).items()},
                            'settings': {str(k).lower(): str(v) for k,v in (settings or {}).items()},
                            'source': source, 'at': time.time()}
        save(data)


def _baseline(result):
    data = load().get('baseline') or {}
    return data if data.get('root') == str(result.root.resolve()) else {}


def setups_for(data: Dict[str, Any], result: Optional[cfgscan.ScanResult]) -> List[Dict[str, Any]]:
    """Setups whose config file is still part of the collection."""
    if result is None:
        return []
    files = {c.relative.lower(): c.relative for c in result.files.values()}
    out = []
    for setup in data.get("setups", []):
        real = files.get(str(setup.get("file", "")).lower())
        if real:
            out.append({"file": real, "maps": [str(m).lower() for m in setup.get("maps") or []]})
    return out


def belongs(setups: List[Dict[str, Any]], map_id: Optional[str]) -> bool:
    """Whether some setup is allowed on ``map_id`` (no maps picked = any map)."""
    if not map_id:
        return False
    from . import maps

    wanted = maps.canonical(map_id).lower()
    for setup in setups:
        picked = setup.get("maps") or []
        if not picked or wanted in {maps.canonical(m).lower() for m in picked}:
            return True
    return False


