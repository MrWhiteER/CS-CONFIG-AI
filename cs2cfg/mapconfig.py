def _plain_name(relative: str) -> str:
    stem = Path(relative).stem
    words = re.sub(r"[_\-.]+", " ", stem).strip()
    return words[:1].upper() + words[1:] if words else relative


# The maps people practise on; any map a setup already names is added too.
COMMON_MAPS = ("de_dust2", "de_mirage", "de_inferno", "de_nuke", "de_ancient",
               "de_anubis", "de_vertigo", "de_overpass", "de_train", "cs_office",
               "cs_italy", "de_overpass_night", "de_ancient_night")


def _map_choices(choices: List[Dict[str, Any]]) -> List[str]:
    out = list(COMMON_MAPS)
    for item in choices:
        for m in item.get("maps", []):
            if m["id"] not in out:
                out.append(m["id"])
    return out


def summary(result: Optional[cfgscan.ScanResult]) -> Dict[str, Any]:
    from . import applynow, keys, maps

    data = load()
    setups = setups_for(data, result)
    picked = {s["file"].lower(): s for s in setups}
    choices = []
    if result is not None:
        for entry in cfgscan.match_profiles(result):
            relative = str(entry["file"])
            found = touched(result, [relative])
            item = picked.get(relative.lower())
            choices.append({
                "file": relative,
                "name": _plain_name(relative),
                "keys": sorted({keys.label(spelled) for spelled, _ in found["keys"].values()}),
                "settings": len(found["settings"]),
                "on": item is not None,
                "maps": [{"id": m, "name": maps.display(m)} for m in (item or {}).get("maps", [])],
            })
    key = applynow.current_key(result) if result is not None else None
    watch = shared()
    return {
        "ok": True,
        "setups": choices,
        "maps": [{"id": k, "name": maps.display(k)} for k in _map_choices(choices)],
        "auto_press": bool(data.get("auto_press", True)),
        "apply_key": keys.label(key) if key else None,
        "live": watch.status() if watch else None,
        "restore_missing": restore_missing(result) if result is not None else [],
        "baseline": _baseline(result) if result is not None else {},
    }


def set_setup(result: Optional[cfgscan.ScanResult], file: str, on: bool,
              map_ids: List[str]) -> Dict[str, Any]:
    from . import maps

    if result is None:
        raise ValueError("Pick your config folder first.")
    if not cfgscan.is_match_profile(result, file):
        raise ValueError("That config can't be used as a map setup.")
    with _STATE_LOCK:
        data = load()
        rest = [s for s in data["setups"] if str(s.get("file", "")).lower() != file.lower()]
        if on:
            clean = []
            for m in map_ids:
                mid = maps.canonical(str(m)).lower()
                if mid and mid not in clean:
                    clean.append(mid)
            rest.append({"file": file, "maps": clean})
        data["setups"] = rest
        if not rest:
            data["needs_reset"] = False
        save(data)
    write_reset(result)
    return summary(result)


def restore_missing(result):
    setups = setups_for(load(), result)
    text = reset_text(result, setups) if setups else ''
    marker = '// Baseline unavailable: '
    return next((line[len(marker):].split(', ') for line in text.splitlines() if line.startswith(marker)), [])
