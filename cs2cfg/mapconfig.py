def _server_only(name: str) -> bool:
    return name.lower().startswith(_SERVER_PREFIXES)


def touched(result: cfgscan.ScanResult, files: List[str]) -> Dict[str, Any]:
    """Keys, scripts and settings the setup files write, with their values."""
    wanted = {f.lower() for f in files}
    keys: Dict[str, Tuple[str, Set[str]]] = {}
    for defs in result.binds.values():
        for bind in defs:
            if bind.file.lower() in wanted:
                physical = cfgscan.physical_key(bind.key)
                spelled, bodies = keys.get(physical, (bind.key, set()))
                bodies.add(bind.body)
                keys[physical] = (spelled, bodies)
    aliases: Set[str] = set()
    for name, defs in result.aliases.items():
        if any(d.file.lower() in wanted for d in defs):
            aliases.add(next(d.name for d in defs if d.file.lower() in wanted))
    settings: Dict[str, Set[str]] = {}
    for name, defs in result.settings.items():
        for d in defs:
            if d.file.lower() in wanted:
                settings.setdefault(d.name, set()).add(d.value)
    return {"keys": keys, "aliases": aliases, "settings": settings}


def _normal_binds(result: cfgscan.ScanResult) -> Tuple[Dict[str, cfgscan.BindDef], Set[str]]:
    """``{physical key: bind}`` the way the next launch leaves the keyboard,
    and the keys it leaves empty -- the same picture the apply key sends."""
    from . import applynow

    chain = cfgscan.startup_chain(result)
    active = applynow._active_profile(result)
    if active is not None:
        from . import layouts

        final, taken_off = cfgscan.profile_layout(
            result, active, layouts.load_pins(result.root).get(active, []))
        return ({cfgscan.physical_key(k): b for k, b in final.items()},
                {cfgscan.physical_key(k) for k in taken_off})
    out: Dict[str, cfgscan.BindDef] = {}
    for key in result.binds:
        winner = cfgscan.startup_bind(result, chain, key)
        if winner is not None:
            out[cfgscan.physical_key(key)] = winner
    return out, set()


def reset_text(result: cfgscan.ScanResult, setups: List[Dict[str, Any]]) -> str:
    """The config that puts every touched key, script and setting back."""
    chain = cfgscan.startup_chain(result)
    found = touched(result, [s["file"] for s in setups])
    normal, taken_off = _normal_binds(result)
    baseline = _baseline(result)
    baseline_keys = baseline.get('keys') or {}
    baseline_settings = baseline.get('settings') or {}
    missing = []

    lines = [
        MARKER,
        "// Puts your normal keys and settings back after a map setup",
        "// (warmup, 5v5 ...). CS CONFIG AI runs it through your apply key",
        "// when you leave the map.",
        "",
    ]
    scripts = []
    for name in sorted(found["aliases"], key=str.lower):
        winner = result.effective_alias(name.lower())
        defs = [d for d in result.aliases.get(name.lower(), [])
                if d.file in chain and not d.nested]
        if defs:
            best = max(defs, key=lambda d: d.order)
            scripts.append(f'alias "{best.name}" "{best.body}"')
        elif winner is not None:
            scripts.append(f'alias "{name}" ""')
    if scripts:
        lines += ["// Scripts"] + scripts + [""]

    settings = []
    for name in sorted(found["settings"], key=str.lower):
        if _server_only(name) or name.lower() in cfglang.EXECUTABLE or name.startswith(("+", "-", "!")):
            continue
        defs = [d for d in result.settings.get(name.lower(), []) if d.file in chain]
        if defs:
            best = max(defs, key=lambda d: d.order)
            settings.append(f'{best.name} "{best.value}"')
        elif name.lower() in baseline_settings:
            value = baseline_settings[name.lower()]
            if not any(c in value for c in ('"', '\n', '\r', ';')):
                settings.append(f'{name} "{value}"')
            else:
                missing.append(name)
        else:
            missing.append(name)
    if settings:
        lines += ["// Settings"] + settings + [""]

    binds = []
    for physical, (spelled, _bodies) in sorted(found["keys"].items()):
        bind = normal.get(physical)
        if bind is not None and physical not in taken_off:
            binds.append(f'bind "{bind.key}" "{bind.body}"')
        elif physical in taken_off:
            binds.append(f'unbind "{spelled}"')
        elif physical in baseline_keys:
            value = baseline_keys[physical]
            if not any(c in value for c in ('"', '\n', '\r')):
                binds.append(f'bind "{spelled}" "{value}"' if value else f'unbind "{spelled}"')
            else:
                missing.append(spelled)
        else:
            from .scriptgen import STOCK_FALLBACK

            stock = STOCK_FALLBACK.get(spelled.lower())
            if stock:
                binds.append(f'bind "{spelled}" "{stock}"')
            else:
                missing.append(spelled)
    if binds:
        lines += ["// Keys"] + binds + [""]
    if missing:
        lines.append('// Baseline unavailable: ' + ', '.join(missing))
        lines.append('echo "CS CONFIG AI: known baseline restored; review missing values in Map configs"')
    else:
        lines.append('echo "CS CONFIG AI: saved normal keys and settings restored"')
    return "\n".join(lines) + "\n"


def reset_path(result: cfgscan.ScanResult) -> Path:
    return Path(result.cfg_root) / FILE_NAME


def write_reset(result: Optional[cfgscan.ScanResult]) -> Optional[Path]:
    """Keep the put-back file in step with the setups and the normal configs.

    Removed when there are no setups, so nothing is left lying about.
    """
    if result is None:
        return None
    target = reset_path(result)
    setups = setups_for(load(), result)
    if not setups:
        try:
            target.unlink()
        except OSError:
            pass
        return None
    text = reset_text(result, setups)
    try:
        previous = target.read_text(encoding="utf-8", errors="replace")
    except OSError:
        previous = ""
    if text != previous:
        target.parent.mkdir(parents=True, exist_ok=True)
        cfglang.write_config_text(target, text, "utf-8")
    return target


def apply_tail(result: Optional[cfgscan.ScanResult]) -> str:
    """The line the apply key file ends with, or ''.

    Only while a put-back is owed: on a map a setup belongs to, pressing the
    apply key must never undo the warmup the player just loaded.
    """
    if result is None or not reset_path(result).is_file():
        return ""
    watch = shared()
    if watch is not None and watch.on_setup_map:
        return ""
    return EXEC_LINE


