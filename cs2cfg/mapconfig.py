# USB HID usage id -> Windows virtual key, for the keys an apply key can be.
def _virtual_key(binding: str) -> Optional[int]:
    low = (binding or "").lower()
    if low.startswith("scancode") and low[8:].isdigit():
        usage = int(low[8:])
        if 58 <= usage <= 69:
            return 0x70 + usage - 58          # F1..F12
        if 4 <= usage <= 29:
            return ord("A") + usage - 4
        if 30 <= usage <= 38:
            return ord("1") + usage - 30
        if usage == 39:
            return ord("0")
        if 89 <= usage <= 97:
            return 0x61 + usage - 89          # Num 1..9
        if usage == 98:
            return 0x60
        return {73: 0x2D, 74: 0x24, 75: 0x21, 76: 0x2E, 77: 0x23, 78: 0x22}.get(usage)
    if len(low) == 1 and low.isalnum():
        return ord(low.upper())
    if low.startswith("f") and low[1:].isdigit() and 1 <= int(low[1:]) <= 12:
        return 0x70 + int(low[1:]) - 1
    return None


def press_key(binding: str) -> bool:
    """Press and let go of one key, the way the keyboard would. Windows only."""
    import sys

    vk = _virtual_key(binding)
    if vk is None or sys.platform != "win32":
        return False
    import ctypes
    from ctypes import wintypes

    from .quickfix import _Input, _KeyInput, INPUT_SIZE

    user32 = ctypes.WinDLL("user32", use_last_error=True)
    user32.SendInput.argtypes = (wintypes.UINT, ctypes.c_void_p, ctypes.c_int)
    user32.SendInput.restype = wintypes.UINT
    user32.MapVirtualKeyW.argtypes = (wintypes.UINT, wintypes.UINT)
    user32.MapVirtualKeyW.restype = wintypes.UINT
    scan = user32.MapVirtualKeyW(vk, 0)
    scancode_flag, up_flag = 0x0008, 0x0002
    events = []
    for up in (False, True):
        item = _Input(type=1)
        item.u.ki = _KeyInput(wVk=0, wScan=scan,
                              dwFlags=scancode_flag | (up_flag if up else 0),
                              time=0, dwExtraInfo=0)
        events.append(item)
    block = (_Input * 2)(*events)
    return user32.SendInput(2, ctypes.byref(block), INPUT_SIZE) == 2


def _cs2_in_front() -> bool:
    try:
        from . import window

        return window.foreground_process() == "cs2.exe"
    except Exception:
        return False


class MapWatch:
    """Reads every game state message and decides when to put things back.

    ``scan`` returns the current config scan; ``refresh`` rewrites the apply
    key file (so its last line follows ``on_setup_map``). Both are injected
    so the logic can be tested without a game.
    """

    def __init__(self, scan: Callable[[], Optional[cfgscan.ScanResult]],
                 refresh: Callable[[Optional[cfgscan.ScanResult]], Any],
                 press: Callable[[str], bool] = press_key,
                 in_front: Callable[[], bool] = _cs2_in_front,
                 capture: Optional[Callable[[], Any]] = None) -> None:
        self.scan = scan
        self.refresh = refresh
        self.press = press
        self.in_front = in_front
        self.capture = capture
        self.on_setup_map = False
        self.map_id = ""
        self.in_menu = False
        self.last_press = 0.0
        self.last_event = ""
        self._lock = threading.Lock()

    def _owed(self, value: Optional[bool] = None) -> bool:
        data = update({"needs_reset": value}) if value is not None else load()
        return bool(data.get("needs_reset"))

    def feed(self, payload: Dict[str, Any]) -> None:
        """One message from the game's state feed."""
        with self._lock:
            game = payload.get("map") or {}
            player = payload.get("player") or {}
            map_id = str(game.get("name") or "").lower()
            self.map_id = map_id
            self.in_menu = not map_id and str(player.get("activity") or "menu") == "menu"
            result = self.scan()
            if not self.on_setup_map and not self._owed() and self.capture:
                self.capture()
            setups = setups_for(load(), result)
            if not setups:
                self.on_setup_map = False
                return
            here = belongs(setups, map_id)
            if here != self.on_setup_map:
                self.on_setup_map = here
                if here:
                    # A setup may be loaded from now on: the put-back is owed
                    # whenever the player leaves, including by a crash.
                    self._owed(True)
                    self.last_event = "on_map"
                else:
                    self.last_event = "left_map"
                write_reset(result)
                self.refresh(result)
            if not here and self.in_menu and self._owed():
                self._put_back(result)

    def _put_back(self, result: Optional[cfgscan.ScanResult]) -> None:
        data = load()
        if not data.get("auto_press", True) or not self.in_front():
            return
        from . import applynow

        if result is None:
            return
        if self.last_event == "partial_restore" and restore_missing(result):
            return
        key = applynow.current_key(result)
        if not key:
            return
        write_reset(result)
        self.refresh(result)
        if self.press(key):
            self.last_press = time.time()
            missing = restore_missing(result)
            self.last_event = "partial_restore" if missing else "put_back"
            if not missing:
                self._owed(False)

    def game_closed(self) -> None:
        """A quit or a crash: the next menu visit puts things back."""
        with self._lock:
            self.on_setup_map = False
            self.in_menu = False
            self.map_id = ""
            self.refresh(self.scan())

    def status(self) -> Dict[str, Any]:
        from . import maps

        return {
            "map": maps.display(self.map_id) if self.map_id else "",
            "on_setup_map": self.on_setup_map,
            "in_menu": self.in_menu,
            "owed": bool(load().get("needs_reset")),
            "last_press": self.last_press,
        }


_shared: Optional[MapWatch] = None


def shared() -> Optional[MapWatch]:
    return _shared


def start(scan, refresh, capture=None) -> MapWatch:
    global _shared
    if _shared is None:
        _shared = MapWatch(scan, refresh, capture=capture)
    return _shared


