"""One key that brings every change made in the app into a running CS2.

CS2 reads the config files once, when it starts. A key layout switched, a
bind changed or a setting saved in the app while a match is on only lands on
disk, so nothing changes in the game until the next launch.

This keeps one plain config file, ``cfg/cs2cfg_apply_now.cfg``, rewritten
after every change the app makes, and binds one key the player picks (in the
autoexec, the same way every other bind gets there) to ``exec`` it. Pressing
that key in game applies everything at once.

The file holds the **full current state** of what the startup configs set --
aliases, settings and binds, exactly as a fresh launch would end up -- rather
than only what changed since the last press. The app cannot see the key being
pressed, so it never knows which changes were already applied; a full state
file is safe to press any number of times and always lands on the same
result. Keys the app took a bind away from are cleared with ``unbind`` so a
removed bind does not linger until the next launch.

Pure config: no process runs beside the game, no game file is touched, and
the bind is a single ``exec`` -- nothing Valve's August 2024 limit on
multi-action binds applies to. Every bind in the file is copied from the
player's own configs, unchanged.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

from . import cfglang, cfgscan

FILE_NAME = cfgscan.APPLY_NOW_FILE
EXEC_NAME = FILE_NAME.rsplit(".", 1)[0]
BIND_COMMAND = f"exec {EXEC_NAME}"
BLOCK_TITLE = "Apply app changes key (cs2-autoconfig)"
MARKER = "// GENERATED BY cs2-autoconfig -- DO NOT EDIT BY HAND"

# Two-token commands that do something when run rather than set a value.
# Re-running them on a key press mid-match (connect, quit, say ...) would be
# anything but "apply my settings", so only real settings are copied over.
_KEEP = {"sensitivity", "volume", "rate", "yaw", "pitch", "developer"}
_NOT_SETTINGS = (cfgscan.KNOWN_ENGINE_COMMANDS | cfglang.EXECUTABLE) - _KEEP

_BIND_LINE = re.compile(r'^\s*(unbind|bind)\s+"([^"]*)"', re.IGNORECASE)


def path_for(result: cfgscan.ScanResult) -> Path:
    return Path(result.cfg_root) / FILE_NAME


def _runs_apply(body: str) -> bool:
    words = (body or "").strip().strip('"').replace(";", " ").split()
    if len(words) != 2 or words[0].lower() != "exec":
        return False
    target = cfglang.normalise_exec_path(words[1])
    return target in (EXEC_NAME, cfglang.normalise_exec_path(FILE_NAME))


def current_key(result: cfgscan.ScanResult) -> Optional[str]:
    """The key the startup configs bind to the apply file, if any."""
    chain = cfgscan.startup_chain(result)
    found = None
    for defs in result.binds.values():
        for b in defs:
            if b.file in chain and _runs_apply(b.body):
                winner = cfgscan._effective_bind(result, chain, b.key)
                if winner is not None and _runs_apply(winner.body):
                    if found is None or b.order > found.order:
                        found = b
    return found.key if found else None


def _same_key(one: str, two: str) -> bool:
    from . import keys

    one, two = (one or "").lower(), (two or "").lower()
    return one == two or keys.label(one).lower() == keys.label(two).lower()


def key_taken(result: cfgscan.ScanResult, key: str) -> Optional[Dict[str, object]]:
    """What the startup configs already run on ``key``, if something real."""
    chain = cfgscan.startup_chain(result)
    for name in result.binds:
        if not _same_key(name, key):
            continue
        winner = cfgscan._effective_bind(result, chain, name)
        if winner is None or winner.file not in chain:
            continue
        runs = (winner.body or "").strip().strip('"')
        if runs and not _runs_apply(runs):
            return {"file": winner.file, "line": winner.line, "runs": runs}
    return None


# ---------------------------------------------------------------------------
# The file itself
# ---------------------------------------------------------------------------

def _previous_keys(text: str) -> Set[str]:
    """Every key an earlier version of the file bound or cleared."""
    out = set()
    for line in (text or "").splitlines():
        match = _BIND_LINE.match(line)
        if match:
            out.add(match.group(2))
    return out


def render(result: cfgscan.ScanResult, previous: str = "") -> str:
    """The full current state of the startup configs, as one config file."""
    chain = cfgscan.startup_chain(result)

    aliases = []
    for name in result.aliases:
        winner = result.effective_alias(name)
        if winner is not None and winner.file in chain:
            aliases.append(winner)
    aliases.sort(key=lambda a: a.order)

    settings = []
    for name in result.settings:
        winner = result.effective_setting(name)
        if winner is None or winner.file not in chain:
            continue
        low = winner.name.lower()
        if low in _NOT_SETTINGS or low.startswith(("+", "-", "!")):
            continue
        settings.append(winner)
    settings.sort(key=lambda s: s.order)

    binds = []
    seen = set()
    for key in result.binds:
        winner = cfgscan._effective_bind(result, chain, key)
        # Two spellings of one key ("e", "scancode8") share one winner.
        if winner is not None and winner.file in chain and id(winner) not in seen:
            seen.add(id(winner))
            binds.append(winner)
    binds.sort(key=lambda b: b.order)

    bound = {b.key.lower() for b in binds}
    cleared = sorted(k for k in _previous_keys(previous)
                     if k.lower() not in bound)

    lines = [
        MARKER,
        "// Applies everything you changed in CS CONFIG AI without restarting",
        "// CS2. Press your apply key in game. The app rewrites this file after",
        "// every change; it always holds your full current setup, so pressing",
        "// the key more than once is harmless.",
        "",
    ]
    if aliases:
        lines.append("// Scripts")
        lines += [f'alias "{a.name}" "{a.body}"' for a in aliases]
        lines.append("")
    if settings:
        lines.append("// Settings")
        lines += [f'{s.name} "{s.value}"' for s in settings]
        lines.append("")
    if cleared:
        lines.append("// Keys you cleared")
        lines += [f'unbind "{k}"' for k in cleared]
        lines.append("")
    if binds:
        lines.append("// Keys")
        lines += [f'bind "{b.key}" "{b.body}"' for b in binds]
        lines.append("")
    lines.append('echo "CS CONFIG AI: your latest changes are now applied"')
    return "\n".join(lines) + "\n"


def refresh(result: Optional[cfgscan.ScanResult]) -> Optional[Path]:
    """Rewrite the file from what is on disk now, if an apply key is set.

    Without a key nothing would ever run it, so no file is left lying about.
    Writes only when the content actually changed.
    """
    if result is None or current_key(result) is None:
        return None
    target = path_for(result)
    try:
        previous = target.read_text(encoding="utf-8", errors="replace")
    except OSError:
        previous = ""
    text = render(result, previous)
    if text != previous:
        target.parent.mkdir(parents=True, exist_ok=True)
        cfglang.write_config_text(target, text, "utf-8")
    return target


# ---------------------------------------------------------------------------
# The key, written into the autoexec
# ---------------------------------------------------------------------------

_BLOCK = re.compile(
    r"(\r?\n// -+\r?\n// " + re.escape(BLOCK_TITLE) + r"\r?\n)(bind \"[^\"]*\")",
)


def set_key_text(result: cfgscan.ScanResult, key: str) -> Tuple[Path, str]:
    """The autoexec's new text with the apply key set to ``key``.

    An existing block of ours has its key swapped in place; otherwise one is
    appended at the end, in the same banner shape ``emit.ensure_exec_line``
    writes, so ``revert`` removes it along with every other block the app
    added.
    """
    if not result.entry_points:
        raise ValueError("no config file loads when CS2 starts, so there is nowhere to put the key")
    entry = result.entry_points[0]
    config = next((c for c in result.files.values() if c.relative == entry), None)
    if config is None:
        raise ValueError("the startup config could not be read")

    text = config.path.read_bytes().decode(config.document.encoding, errors="replace")
    newline = "\r\n" if "\r\n" in text else "\n"
    line = f'bind "{key}" "{BIND_COMMAND}"'

    if _BLOCK.search(text):
        return config.path, _BLOCK.sub(lambda m: m.group(1) + f'bind "{key}"', text, count=1)

    block = newline.join([
        "",
        "// ---------------------------------------------",
        f"// {BLOCK_TITLE}",
        line,
        "// ---------------------------------------------",
        "",
    ])
    if text and not text.endswith(("\n", "\r")):
        text += newline
    return config.path, text + block


def status(result: Optional[cfgscan.ScanResult]) -> Dict[str, object]:
    from . import keys

    if result is None:
        return {"ready": False, "key": None, "key_label": None}
    key = current_key(result)
    return {
        "ready": key is not None,
        "key": key,
        "key_label": keys.label(key) if key else None,
        "file": str(path_for(result)),
    }


def key_labels(result: Optional[cfgscan.ScanResult]) -> List[str]:
    """Every key that brings changes into a running game, as players read them.

    The apply key above, plus any older "reload my configs" key the
    collection already had.
    """
    from . import keys

    if result is None:
        return []
    out: List[str] = []
    key = current_key(result)
    if key:
        out.append(keys.label(key))
    legacy = cfgscan.existing_apply_script(result) or {}
    for bound in legacy.get("bound_to") or []:
        label = keys.label(bound)
        if label not in out:
            out.append(label)
    return out
